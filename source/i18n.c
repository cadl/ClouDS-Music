static _Atomic int current_language = APP_LANGUAGE_CHINESE;

bool i18n_language_valid(int language) {
    return language >= APP_LANGUAGE_CHINESE &&
           language < APP_LANGUAGE_COUNT;
}

void i18n_set_language(AppLanguage language) {
    if (!i18n_language_valid(language)) language = APP_LANGUAGE_CHINESE;
    atomic_store_explicit(&current_language, language, memory_order_relaxed);
}

AppLanguage i18n_get_language(void) {
    return (AppLanguage)atomic_load_explicit(&current_language,
                                             memory_order_relaxed);
}

const char *i18n_text(const char *chinese) {
    if (!chinese || i18n_get_language() == APP_LANGUAGE_CHINESE)
        return chinese;
    const unsigned char *cursor = (const unsigned char *)chinese;
    while (*cursor && *cursor < 0x80U) cursor++;
    if (!*cursor) return chinese;
    for (size_t i = 0; i < sizeof(TRANSLATIONS) / sizeof(TRANSLATIONS[0]);
         i++) {
        if (strcmp(chinese, TRANSLATIONS[i].chinese) == 0)
            return TRANSLATIONS[i].english;
    }
    return chinese;
}

int i18n_vsnprintf(char *output, size_t output_size,
                   const char *format, va_list args) {
    return vsnprintf(output, output_size, i18n_text(format), args);
}

int i18n_snprintf(char *output, size_t output_size,
                  const char *format, ...) {
    va_list args;
    va_start(args, format);
    int result = i18n_vsnprintf(output, output_size, format, args);
    va_end(args);
    return result;
}
